// Data model and SVG layout for MorphismDiagram.astro: the factor diagrams of Carlisle, Shah,
// Stern and VanKoughnett, "Categorical Foundations for CuTe Layouts" (arXiv:2601.05972). A
// nested-tuple morphism f : S → T is drawn as two columns of entries (S on the left, T on the
// right, listed bottom to top as in the paper) with an arrow from each entry of S to the entry of
// T it lands on, or to ∗ when it is discarded. Several columns in a row form a chain (pasted
// diagrams f then g); "refine" links draw a refinement as a fan from one coarse entry to the fine
// entries that multiply to it. Mode brackets with their sizes are drawn on the outer columns.
// Figure data is generated by a script from Colfax's `tract` package (cuteCategoryFigures.ts).

/** A nested tuple whose leaves are display strings ("6", "7/24"). */
export type Nested = string | Nested[];

export interface DiagramColumn {
	tuple: Nested;
	/** Hover text per leaf, in flattened order (bottom to top). */
	tips?: string[];
}

export type DiagramLink =
	| {
			kind: "map";
			/** Per source leaf: 1-based target leaf, or 0 for ∗ (discarded). */
			map: number[];
			/** Morphism name drawn under the arrows, e.g. "f", "g′∘f′". */
			label?: string;
			/** Hover text per arrow. */
			tips?: string[];
	  }
	| {
			kind: "refine";
			/** Which neighbour holds the coarse tuple; the other holds the fine leaves. */
			coarse: "left" | "right";
			/** Number of fine leaves per coarse leaf; they cover a prefix of the fine column. */
			counts: number[];
			label?: string;
	  };

export interface DiagramChain {
	columns: DiagramColumn[];
	/** columns.length − 1 links, between neighbouring columns. */
	links: DiagramLink[];
	/** Line under the chain, usually the encoded layout. */
	caption?: string;
	/** Draw ⇝ before this chain (the result of an operation). */
	lead?: boolean;
}

export interface DiagramStep {
	title: string;
	chains: DiagramChain[];
	note?: string;
}

export interface DiagramFigure {
	tab?: string;
	steps: DiagramStep[];
}

// Geometry in px (mono text at 12px ≈ 7.3px per character).
export const GEOM = {
	row: 28,
	boxH: 22,
	char: 7.3,
	padX: 7,
	minBox: 26,
	mapGap: 80,
	refineGap: 52,
	bracket: 7,
	labelChar: 6.7,
	chainGap: 48,
	top: 10,
	side: 6,
};

export function flat(t: Nested): string[] {
	return typeof t === "string" ? [t] : t.flatMap(flat);
}

/** Value of "6" or "7/24"; NaN if not a number. */
export function parseEntry(s: string): number {
	const [a, b = "1"] = s.split("/");
	return Number(a) / Number(b);
}

export interface Bracket {
	start: number;
	end: number;
	depth: number;
	label?: string;
}

/** Brackets around every non-leaf mode (depth 1 = top-level modes), labelled with their size. */
export function bracketsOf(t: Nested): { brackets: Bracket[]; maxDepth: number } {
	const brackets: Bracket[] = [];
	let maxDepth = 0;
	const walk = (node: Nested, start: number, depth: number): number => {
		if (typeof node === "string") return start + 1;
		let i = start;
		for (const child of node) i = walk(child, i, depth + 1);
		if (depth >= 1) {
			const size = flat(node)
				.map(parseEntry)
				.reduce((p, v) => p * v, 1);
			brackets.push({
				start,
				end: i - 1,
				depth,
				label: depth === 1 && Number.isInteger(size) ? String(size) : undefined,
			});
			maxDepth = Math.max(maxDepth, depth);
		}
		return i;
	};
	walk(t, 0, 0);
	return { brackets, maxDepth };
}

/** Problems with a step's data; an empty list means it can be drawn. */
export function validateStep(step: DiagramStep): string[] {
	const errs: string[] = [];
	step.chains.forEach((chain, c) => {
		if (chain.links.length !== chain.columns.length - 1)
			errs.push(`chain ${c}: ${chain.links.length} links for ${chain.columns.length} columns`);
		chain.links.forEach((link, k) => {
			const left = flat(chain.columns[k]?.tuple ?? []);
			const right = flat(chain.columns[k + 1]?.tuple ?? []);
			if (link.kind === "map") {
				if (link.map.length !== left.length)
					errs.push(`chain ${c} link ${k}: map has ${link.map.length} entries, source ${left.length}`);
				link.map.forEach((a, i) => {
					if (a < 0 || a > right.length) errs.push(`chain ${c} link ${k}: target ${a} out of range`);
					else if (a > 0 && left[i] !== right[a - 1])
						errs.push(`chain ${c} link ${k}: ${left[i]} → ${right[a - 1]} sizes differ`);
				});
				if (new Set(link.map.filter((a) => a > 0)).size !== link.map.filter((a) => a > 0).length)
					errs.push(`chain ${c} link ${k}: two arrows hit one entry`);
			} else {
				const coarse = link.coarse === "left" ? left : right;
				const fine = link.coarse === "left" ? right : left;
				if (link.counts.length !== coarse.length)
					errs.push(`chain ${c} link ${k}: ${link.counts.length} counts for ${coarse.length} coarse entries`);
				let at = 0;
				link.counts.forEach((n, ci) => {
					const part = fine.slice(at, at + n).map(parseEntry);
					const prod = part.reduce((p, v) => p * v, 1);
					if (part.length !== n || Math.abs(prod - parseEntry(coarse[ci])) > 1e-9)
						errs.push(`chain ${c} link ${k}: fine entries ${at}..${at + n - 1} do not multiply to ${coarse[ci]}`);
					at += n;
				});
			}
		});
	});
	return errs;
}

export interface BoxShape {
	key: string;
	x: number;
	y: number;
	w: number;
	text: string;
	tip?: string;
}
export interface ArrowShape {
	d: string;
	head: string;
	from: string;
	to: string;
	tip?: string;
	hue: number;
}
export interface TextShape {
	x: number;
	y: number;
	text: string;
	anchor: "start" | "middle" | "end";
	kind: "bracket" | "label" | "caption" | "star" | "lead";
}
export interface StepLayout {
	width: number;
	height: number;
	boxes: BoxShape[];
	arrows: ArrowShape[];
	fans: { d: string; from: string; to: string }[];
	brackets: string[];
	texts: TextShape[];
}

const hue = (k: number) => (25 + k * 137.508) % 360;
const r1 = (v: number) => Math.round(v * 10) / 10;

function arrowHead(x: number, y: number, cx: number, cy: number): string {
	const len = Math.hypot(x - cx, y - cy) || 1;
	const ux = (x - cx) / len;
	const uy = (y - cy) / len;
	const bx = x - 6.5 * ux;
	const by = y - 6.5 * uy;
	return `M${r1(x)} ${r1(y)}L${r1(bx - 3.4 * uy)} ${r1(by + 3.4 * ux)}L${r1(bx + 3.4 * uy)} ${r1(by - 3.4 * ux)}Z`;
}

/** Positions of every box, arrow, fan, bracket and label of one step. */
export function layoutStep(step: DiagramStep): StepLayout {
	const G = GEOM;
	const allCols = step.chains.flatMap((c) => c.columns);
	const maxLeaves = Math.max(1, ...allCols.map((c) => flat(c.tuple).length));
	const hasStar = step.chains.some((c) => c.links.some((l) => l.kind === "map" && l.map.includes(0)));
	const hasLabel = step.chains.some((c) => c.links.some((l) => l.label));
	const hasCaption = step.chains.some((c) => c.caption);
	const rowsBottom = G.top + maxLeaves * G.row;
	const starY = rowsBottom + 12;
	const labelY = rowsBottom + (hasStar ? 36 : 16);
	const captionY = hasLabel ? labelY + 20 : labelY;
	const height = hasCaption ? captionY + 10 : hasLabel ? labelY + 8 : rowsBottom + (hasStar ? 24 : 6);
	const yOf = (i: number) => G.top + (maxLeaves - 1 - i) * G.row + G.row / 2;

	const out: StepLayout = { width: 0, height, boxes: [], arrows: [], fans: [], brackets: [], texts: [] };
	let cursor = G.side;

	step.chains.forEach((chain, c) => {
		if (c > 0) {
			if (chain.lead)
				out.texts.push({ x: cursor + G.chainGap / 2, y: G.top + (maxLeaves * G.row) / 2 + 6, text: "⇝", anchor: "middle", kind: "lead" });
			cursor += G.chainGap;
		}
		// First pass: x of each column relative to the chain start.
		const last = chain.columns.length - 1;
		const cols: { x: number; w: number; leaves: string[]; side: "left" | "right" | null; br: ReturnType<typeof bracketsOf>; space: number }[] = [];
		let x = 0;
		chain.columns.forEach((col, k) => {
			const leaves = flat(col.tuple);
			const w = Math.max(G.minBox, Math.max(...leaves.map((s) => s.length)) * G.char + 2 * G.padX);
			const br = bracketsOf(col.tuple);
			const side = k === 0 ? "left" : k === last ? "right" : null;
			const labelW = Math.max(0, ...br.brackets.map((b) => (b.label ? b.label.length * G.labelChar + 4 : 0)));
			const space = side && br.maxDepth > 0 ? br.maxDepth * G.bracket + 5 + labelW : 0;
			if (side === "left") x += space;
			cols.push({ x, w, leaves, side, br, space });
			x += w + (side === "right" ? space : 0);
			if (k < last) x += chain.links[k].kind === "map" ? G.mapGap : G.refineGap;
		});
		const contentW = x;
		const captionW = (chain.caption?.length ?? 0) * G.labelChar;
		const chainW = Math.max(contentW, captionW);
		const shift = cursor + (chainW - contentW) / 2;
		for (const col of cols) col.x += shift;
		const key = (k: number, i: number) => `${c}-${k}-${i}`;

		cols.forEach((col, k) => {
			col.leaves.forEach((text, i) => {
				out.boxes.push({ key: key(k, i), x: r1(col.x), y: r1(yOf(i) - G.boxH / 2), w: r1(col.w), text, tip: chain.columns[k].tips?.[i] });
			});
			if (!col.side) return;
			const dir = col.side === "left" ? -1 : 1;
			const edge = col.side === "left" ? col.x : col.x + col.w;
			for (const b of col.br.brackets) {
				const off = 4 + (col.br.maxDepth - b.depth) * G.bracket + G.bracket - 2;
				const bx = edge + dir * off;
				const yTop = yOf(b.end) - G.boxH / 2 + 1;
				const yBot = yOf(b.start) + G.boxH / 2 - 1;
				const tick = -dir * 3.5;
				out.brackets.push(`M${r1(bx + tick)} ${r1(yTop)}H${r1(bx)}V${r1(yBot)}H${r1(bx + tick)}`);
				if (b.label)
					out.texts.push({
						x: r1(edge + dir * (4 + col.br.maxDepth * G.bracket + 2)),
						y: r1((yTop + yBot) / 2 + 4),
						text: b.label,
						anchor: col.side === "left" ? "end" : "start",
						kind: "bracket",
					});
			}
		});

		chain.links.forEach((link, k) => {
			const L = cols[k];
			const R = cols[k + 1];
			const x1 = L.x + L.w;
			const x2 = R.x;
			if (link.label)
				out.texts.push({ x: r1((x1 + x2) / 2), y: labelY, text: link.label, anchor: "middle", kind: "label" });
			if (link.kind === "map") {
				let star = false;
				link.map.forEach((a, i) => {
					const y1 = yOf(i);
					let d: string;
					let head: string;
					if (a > 0) {
						const y2 = yOf(a - 1);
						const dx = x2 - 1 - x1;
						const c1x = x1 + dx * 0.5;
						const c2x = x2 - 1 - dx * 0.5;
						d = `M${r1(x1)} ${r1(y1)}C${r1(c1x)} ${r1(y1)} ${r1(c2x)} ${r1(y2)} ${r1(x2 - 1)} ${r1(y2)}`;
						head = arrowHead(x2 - 1, y2, c2x, y2);
					} else {
						star = true;
						const sx = R.x + R.w / 2;
						const sy = starY - 7;
						d = `M${r1(x1)} ${r1(y1)}C${r1(x1 + (sx - x1) * 0.6)} ${r1(y1)} ${r1(sx)} ${r1(sy - 16)} ${r1(sx)} ${r1(sy)}`;
						head = arrowHead(sx, sy, sx, sy - 16);
					}
					out.arrows.push({ d, head, from: key(k, i), to: a > 0 ? key(k + 1, a - 1) : `${c}-${k + 1}-star`, tip: link.tips?.[i], hue: hue(i) });
				});
				if (star) out.texts.push({ x: r1(R.x + R.w / 2), y: r1(starY + 5), text: "∗", anchor: "middle", kind: "star" });
			} else {
				let at = 0;
				const coarse = link.coarse === "left" ? L : R;
				const kc = link.coarse === "left" ? k : k + 1;
				const kf = link.coarse === "left" ? k + 1 : k;
				link.counts.forEach((n, ci) => {
					for (let fi = at; fi < at + n; fi++) {
						const [ax, ay, bx, by] =
							link.coarse === "left" ? [coarse.x + coarse.w, yOf(ci), x2, yOf(fi)] : [x1, yOf(fi), coarse.x, yOf(ci)];
						out.fans.push({ d: `M${r1(ax)} ${r1(ay)}L${r1(bx)} ${r1(by)}`, from: key(kc, ci), to: key(kf, fi) });
					}
					at += n;
				});
			}
		});

		if (chain.caption)
			out.texts.push({ x: r1(cursor + chainW / 2), y: captionY, text: chain.caption, anchor: "middle", kind: "caption" });
		cursor += chainW;
	});
	out.width = Math.ceil(cursor + G.side);
	return out;
}
