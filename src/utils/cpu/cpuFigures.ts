/** Piecewise-linear lookup in log2(KiB), for LineChart. */
export function chaseAt(table: [number, number][], log2kib: number): number {
	const xs = table.map(([k]) => Math.log2(k));
	if (log2kib <= xs[0]) return table[0][1];
	for (let i = 1; i < xs.length; i++) {
		if (log2kib <= xs[i]) {
			const f = (log2kib - xs[i - 1]) / (xs[i] - xs[i - 1]);
			return table[i - 1][1] + f * (table[i][1] - table[i - 1][1]);
		}
	}
	return table[table.length - 1][1];
}
export const CHASE_X = CHASE_NS_4K.map(([k]) => Math.log2(k));

