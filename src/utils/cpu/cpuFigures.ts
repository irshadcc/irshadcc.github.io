const LOAD_LAT = 4;
const FADD_LAT = 3;

function sumProgram(n: number, accs: number): Instr[] {
	const p: Instr[] = [];
	for (let k = 0; k < n; k++) {
		p.push({
			text: `vmovsd x${k}, [rsi+${8 * k}]`,
			kind: "load",
			dst: `x${k}`,
			srcs: [],
			lat: LOAD_LAT,
		});
		const a = `acc${k % accs}`;
		p.push({
			text: `vaddsd ${a}, ${a}, x${k}`,
			kind: "fp",
			dst: a,
			srcs: [a, `x${k}`],
			lat: FADD_LAT,
		});
	}
	return p;
}

